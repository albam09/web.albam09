import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const F=createRequire(import.meta.url)('../../js/forum-schema.js');
const row={slug:'karaoke1-schema-test',status:'published',author_id:'public-author-test',profiles:{nickname:'공개 닉네임'},created_at:'2026-10-11T15:11:23.855001+00:00',published_at:'2026-10-11T15:12:15.099022+00:00',content:'공개된 실제 본문',title:'탐험기'};
const schema=await F.post(row);
assert.deepEqual(F.issues(schema),[]);
assert.equal(schema.author.name,'공개 닉네임');
assert.match(schema.author.url,/\/explore\/author\/member-[a-f0-9]{24}\/$/);
assert.equal((await F.author({...row,slug:'another-post'})).url,schema.author.url,'Same author has one public profile');
assert.notEqual((await F.author({...row,author_id:'different-user'})).url,schema.author.url);
const noNickname=await F.post({...row,profiles:{nickname:'  '}});
assert.equal(noNickname.author.name,'광주버블여지도 회원');
assert.equal((await F.post({...row,published_at:'invalid'})).datePublished,new Date(row.created_at).toISOString());
assert.equal(await F.post({...row,published_at:null,created_at:null}),null,'Never invent a publication date');
assert.equal(F.iso(null),null,'Do not turn null into the Unix epoch');
assert.equal(await F.post({...row,status:'pending'}),null,'Private posts must not become public forum schema');
assert.equal(await F.post({...row,is_deleted:true}),null);
assert.equal(await F.post({...row,content:'',images:[]}),null,'Empty forum markup is not emitted');
const comment={id:'reply-1',status:'published',author_id:'comment-author',profiles:{nickname:'댓글 작성자'},content:'공개 댓글',created_at:row.created_at};
const replies=await F.post(row,[comment,{...comment,id:'private',status:'pending'},{...comment,id:'no-date',created_at:''}]);
assert.equal(replies.comment.length,1);
assert.equal(replies.comment[0].author.name,'댓글 작성자');
assert.ok(replies.comment[0].author.url);
assert.deepEqual(F.issues(replies),[]);
assert.deepEqual(F.issues({...schema,author:null}),['author.name','author.url']);
console.log('PASS: author, real dates, canonical URLs, public profiles and valid comments share one schema rule; incomplete/private markup excluded');
